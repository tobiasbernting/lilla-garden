// Hilda's six levels, drawn as text: each segment is one screen (20 tiles of 8 pixels) and 18 rows,
// written from the top row that has anything in it down to the bottom (missing top rows are air).
//
//   .  air          #  ground        B  block (hay bale, log, chimney, snow block)
//   =  board you can jump up through ~  water        *  thorns / icicles     x  hay that gives way
//   i  ice          ^^ springy haystack / mushroom / snowbank                 L  clothes line (bouncy)
//   u  chimney top (warm air rises above it)
//   o  egg          G  golden egg    f  fox           h  hedgehog            c  crow (sitting)
//   b  crow flying  M---  moving bale (the dashes are how far it goes)       V | lift (the bars below)
//   S  scarecrow (checkpoint)        H  hen house (its bottom-left corner)   P  start
//   l  lantern      s  sign (hold to flap)   n  snowman

export type Place = 'meadow' | 'forest' | 'barn' | 'roof' | 'winter' | 'night';

export interface LevelDef {
  name: string;
  place: Place;
  /** Which tune plays. */
  tune: number;
  /** Seconds; finishing faster gives a time bonus. */
  par: number;
  wind?: boolean;
  dark?: boolean;
  snow?: boolean;
  map: string[];
}

const ROWS = 18;

/** Glue screens together; each one is padded with air at the top to 18 rows. */
function build(...segs: string[][]): string[] {
  const out: string[] = Array.from({ length: ROWS }, () => '');
  for (const seg of segs) {
    const w = Math.max(...seg.map((r) => r.length));
    const rows = [...Array.from({ length: Math.max(0, ROWS - seg.length) }, () => ''), ...seg].slice(-ROWS);
    for (let r = 0; r < ROWS; r++) out[r] += rows[r]!.padEnd(w, '.');
  }
  return out;
}

