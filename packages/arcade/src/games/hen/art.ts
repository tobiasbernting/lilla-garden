function hen(wing: Sprite | null, wx: number, wy: number, legs: Sprite, blink = false, dy = 0): Sprite {
  let s = blank(16, 16);
  s = over(s, HEN_BODY, 0, dy);
  if (blink) s = over(s, spr(['0', '3']), 12, 4 + dy);
  if (wing) s = over(s, wing, wx, wy + dy);
  s = over(s, legs, 0, 14);
  return s;
}

